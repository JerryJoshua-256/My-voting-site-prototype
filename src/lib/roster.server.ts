const byMatric = new Map<string, { matric: string; name: string }>(
  ROSTER.map((student) => [student.matric, student]),
);

export function normalizeMatric(raw: string): string | null {
  const stripped = raw.trim().toUpperCase().replace(/[\s\-/]+/g, "");
  const match = stripped.match(/^URP(\d{2})(\d{3,4})$/);
  if (!match) return null;
  return `URP/${match[1]}/${match[2]}`;
}

export function findStudent(raw: string) {
  const matric = normalizeMatric(raw);
  if (!matric) return null;
  return byMatric.get(matric) ?? null;
}

export function displayName(name: string): string {
  return name
    .toLowerCase()
    .split(" ")
    .map((word) =>
      word
        .split("-")
        .map((part) => (part ? part.charAt(0).toUpperCase() + part.slice(1) : part))
        .join("-"),
    )
    .join(" ");
}
